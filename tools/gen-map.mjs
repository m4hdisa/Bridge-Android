// Writes WorldData.kt for Bridge for Android: the land as a grid of dots for the map on the
// dashboard, each country's outline (to highlight where the phone is and where traffic leaves),
// and a point inside each country, from Natural Earth's 1:110m land and countries (public domain,
// naturalearthdata.com). Usage:
//   node tools/gen-map.mjs ne_110m_land.geojson ne_110m_admin_0_countries.geojson app/src/main/java/io/github/m4hdisa/bridge/ui/WorldData.kt
import { readFileSync, writeFileSync } from 'node:fs'

const [landFile, countriesFile, out] = process.argv.slice(2)
const COLS = 180
const TOP = 78
const BOTTOM = -56
const STEP = 360 / COLS
const ROWS = Math.round((TOP - BOTTOM) / STEP)

const polygons = (g) => (g.type === 'Polygon' ? [g.coordinates] : g.coordinates)
const rings = []
for (const f of JSON.parse(readFileSync(landFile, 'utf8')).features) for (const p of polygons(f.geometry)) rings.push(p[0])
const inside = (x, y, ring) => {
  let c = false
  for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) {
    const [xi, yi] = ring[i]
    const [xj, yj] = ring[j]
    if (yi > y !== yj > y && x < ((xj - xi) * (y - yi)) / (yj - yi) + xi) c = !c
  }
  return c
}
const rows = []
for (let r = 0; r < ROWS; r++) {
  const lat = TOP - (r + 0.5) * STEP
  let bits = ''
  for (let c = 0; c < COLS; c++) bits += rings.some((ring) => inside(-180 + (c + 0.5) * STEP, lat, ring)) ? '1' : '0'
  // Hex, four dots a character.
  rows.push(bits.match(/.{4}/g).map((b) => parseInt(b, 2).toString(16)).join(''))
}

const points = []
const shapes = []
for (const f of JSON.parse(readFileSync(countriesFile, 'utf8')).features) {
  const p = f.properties
  const code = p.ISO_A2_EH !== '-99' ? p.ISO_A2_EH : p.ISO_A2
  if (!/^[A-Z]{2}$/.test(code)) continue
  points.push(`"${code}" to (${p.LABEL_Y.toFixed(1)} to ${p.LABEL_X.toFixed(1)})`)
  // Outer rings only, to a tenth of a degree, without points that land on the one before.
  const outline = polygons(f.geometry)
    .map((poly) => {
      const pts = []
      for (const [x, y] of poly[0]) {
        const pt = `${x.toFixed(1)},${y.toFixed(1)}`
        if (pts[pts.length - 1] !== pt) pts.push(pt)
      }
      return pts.length >= 3 ? pts.join(' ') : ''
    })
    .filter(Boolean)
    .join(';')
  if (outline) shapes.push(`"${code}" to "${outline}"`)
}
// Small places Natural Earth's 1:110m map leaves out, where servers often are.
const extra = { SG: [1.35, 103.8], HK: [22.3, 114.2], BH: [26.1, 50.5], MT: [35.9, 14.4], LU: [49.8, 6.1], MC: [43.7, 7.4], LI: [47.2, 9.6], AD: [42.5, 1.5], SM: [43.9, 12.4], MU: [-20.3, 57.6], MV: [3.2, 73.2] }
for (const [code, [lat, lon]] of Object.entries(extra)) if (!points.some((p) => p.startsWith(`"${code}"`))) points.push(`"${code}" to (${lat} to ${lon})`)

writeFileSync(
  out,
  `package io.github.m4hdisa.bridge.ui

/**
 * The world for the dashboard's map, from Natural Earth's 1:110m data (public domain).
 * Generated by tools/gen-map.mjs; don't edit by hand.
 */
object WorldData {
    /** Land, a dot every ${STEP} degrees from ${TOP}°N to ${-BOTTOM}°S and 180°W eastwards: ${ROWS} rows of ${COLS} dots, four to a hex digit. */
    const val COLS = ${COLS}
    const val TOP = ${TOP}.0
    const val STEP = ${STEP}.0
    val LAND = listOf(
${rows.map((r) => `        "${r}",`).join('\n')}
    )

    /** A point inside each country (latitude to longitude), where its name would go on a map. */
    val PLACES: Map<String, Pair<Double, Double>> = mapOf(
${points.map((p) => `        ${p},`).join('\n')}
    )

    /** Each country's outline: rings split by ";", points "longitude,latitude" split by spaces. */
    val SHAPES: Map<String, String> by lazy {
        mapOf(
${shapes.map((p) => `            ${p},`).join('\n')}
        )
    }
}
`,
)
console.log(`${ROWS} rows, ${points.length} countries, ${shapes.length} outlines`)
